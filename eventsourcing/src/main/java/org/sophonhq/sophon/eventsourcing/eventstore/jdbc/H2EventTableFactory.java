package org.sophonhq.sophon.eventsourcing.eventstore.jdbc;

/**
 * Jdbc table factory for H2 databases.
 *
 * @since sophon-1.2.0
 */
public class H2EventTableFactory extends AbstractEventTableFactory {

    /**
     * Singleton H2EventTableFactory instance
     */
    public static final H2EventTableFactory INSTANCE = new H2EventTableFactory();

    /**
     * Default constructor of the factory
     */
    protected H2EventTableFactory() {
    }

    @Override
    protected String idColumnType() {
        return "BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 0 INCREMENT BY 1)";
    }

    @Override
    protected String payloadType() {
        return "BLOB";
    }
}
